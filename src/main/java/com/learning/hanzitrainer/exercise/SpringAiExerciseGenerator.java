package com.learning.hanzitrainer.exercise;

import com.learning.hanzitrainer.common.StructuredReply;
import com.learning.hanzitrainer.common.UnreadableReplyException;
import com.learning.hanzitrainer.word.WordDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.core.io.Resource;

import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Asks the configured chat model for sentence exercises. The instructions per type are the system prompt
 * ({@code prompts/gen-*.st}); the words and the count go into the user message.
 */
public class SpringAiExerciseGenerator implements ExerciseGenerator {

    private static final Logger log = LoggerFactory.getLogger(SpringAiExerciseGenerator.class);

    private final ChatClient chatClient;
    private final Map<ExerciseType, Resource> systemPrompts;
    private final String modelName;

    /** @param systemPrompts one per LLM type */
    public SpringAiExerciseGenerator(ChatClient chatClient, Map<ExerciseType, Resource> systemPrompts,
                                     String modelName) {
        this.chatClient = chatClient;
        this.systemPrompts = Map.copyOf(systemPrompts);
        this.modelName = modelName;
    }

    @Override
    public List<GeneratedExercise> generate(ExerciseType type, List<WordDto> targetWords, Set<String> allowedWords,
                                            int count) {
        Resource systemPrompt = systemPrompts.get(type);
        if (systemPrompt == null) {
            throw new IllegalArgumentException(type + " is not generated by the LLM");
        }
        Class<? extends Batch> shape = switch (type) {
            case FILL_BLANK -> FillBlanks.class;
            case WORD_ORDER -> WordOrders.class;
            case TRANSLATION -> Translations.class;
            default -> throw new IllegalArgumentException(type + " is not generated by the LLM");
        };
        StructuredReply<? extends Batch> reply = StructuredReply.call(chatClient.prompt()
                .system(systemPrompt)
                .user(userText(targetWords, allowedWords, count)), shape);
        LlmUsage.log(log, "Generating " + type, modelName, reply.response());
        Batch batch = reply.entity();
        if (batch == null || batch.exercises() == null) {
            throw new UnreadableReplyException("Model " + modelName + " returned no exercises");
        }
        return batch.exercises().stream().filter(Objects::nonNull).map(GeneratedExercise.class::cast).toList();
    }

    static String userText(List<WordDto> targetWords, Set<String> allowedWords, int count) {
        String targets = targetWords.stream()
                .map(w -> "- " + w.hanzi() + " (" + w.pinyin() + "): " + Objects.requireNonNullElse(w.meaningEn(), "?"))
                .collect(Collectors.joining("\n"));
        return "Write " + count + " exercise" + (count == 1 ? "" : "s") + ".\n\n"
                + "Target words (every exercise uses at least one):\n" + targets + "\n\n"
                + "Allowed words (use no other words):\n" + String.join(" ", allowedWords);
    }

    @Override
    public String modelName() {
        return modelName;
    }

    private interface Batch {
        List<? extends GeneratedExercise> exercises();
    }

    record FillBlanks(List<GeneratedExercise.FillBlank> exercises) implements Batch {
    }

    record WordOrders(List<GeneratedExercise.WordOrder> exercises) implements Batch {
    }

    record Translations(List<GeneratedExercise.Translation> exercises) implements Batch {
    }
}
